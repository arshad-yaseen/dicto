import { existsSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { type Kind, type Node, parse, pluralCategories, sourceLocale } from "../message.ts";
import { type Problem, scan } from "./scan.ts";

export const folder = "locales";

const header = "// Generated by dicto. Do not edit.\n";

export type Catalog =
  | { locale: string; translations: Map<string, string> }
  | { locale: string; error: string };

export interface Sync {
  messages: string[];
  problems: Problem[];
  complete: boolean;
  catalogs: Catalog[];
}

export interface Verdict {
  locale: string;
  untranslated: number;
  invalid: { message?: string; reason: string }[];
}

interface Shape {
  marks: Set<string>;
  choices: { name: string; kind: Kind; options: Set<string> }[];
}

export function sync(root: string, { prune }: { prune: boolean }): Sync {
  const { files, problems } = scan(root);
  const messages = [...new Set(files.flatMap((file) => file.messages))].sort();
  const complete = problems.every((problem) => problem.kind !== "syntax");
  const catalogs = complete ? update(root, messages, prune) : [];
  return { messages, problems, complete, catalogs };
}

/**
 * Adds the messages each catalog lacks and, with `prune`, removes the ones not in `messages`.
 * Rewrites the generated module, and writes a file only when it changes.
 */
export function update(root: string, messages: string[], prune: boolean): Catalog[] {
  const directory = join(root, folder);
  if (!existsSync(directory)) return [];
  const catalogs = readdirSync(directory)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => updateCatalog(join(directory, name), messages, prune));
  const locales = catalogs.flatMap((catalog) => ("error" in catalog ? [] : [catalog.locale]));
  write(join(directory, "index.js"), loaders(locales));
  write(join(directory, "index.d.ts"), declarations(locales, messages));
  return catalogs;
}

export function verify({ messages, catalogs }: Sync): Verdict[] {
  const source: Verdict = { locale: sourceLocale, untranslated: 0, invalid: [] };
  const shapes = new Map<string, Shape>();
  for (const message of messages) {
    const shape = shapeOf(message);
    if (typeof shape === "string") source.invalid.push({ message, reason: shape });
    else shapes.set(message, shape);
  }
  const verdicts = catalogs.map((catalog): Verdict => {
    const { locale } = catalog;
    if ("error" in catalog) {
      return { locale, untranslated: 0, invalid: [{ reason: catalog.error }] };
    }
    const verdict: Verdict = { locale, untranslated: 0, invalid: [] };
    for (const [message, shape] of shapes) {
      const translation = catalog.translations.get(message);
      if (!translation) {
        verdict.untranslated += 1;
        continue;
      }
      const reason = mismatch(shape, shapeOf(translation), locale);
      if (reason) verdict.invalid.push({ message, reason });
    }
    return verdict;
  });
  return source.invalid.length > 0 ? [source, ...verdicts] : verdicts;
}

function updateCatalog(path: string, messages: string[], prune: boolean): Catalog {
  const locale = basename(path, ".json");
  if (!isLocaleTag(locale)) return { locale, error: "is not a locale" };
  const text = readFileSync(path, "utf8");
  const translations = parseCatalog(text);
  if (!translations) return { locale, error: "is not a JSON object of strings" };
  const keys = prune ? messages : [...new Set([...messages, ...translations.keys()])].sort();
  write(path, serialize(keys, translations), text);
  return { locale, translations };
}

function shapeOf(text: string): Shape | string {
  let nodes: Node[];
  try {
    nodes = parse(text);
  } catch (error) {
    return `does not parse: ${(error as Error).message}`;
  }
  const shape: Shape = { marks: new Set(), choices: [] };
  const visit = (node: Node): void => {
    if (typeof node === "string" || node.type === "pound") return;
    if (node.type === "tag") {
      shape.marks.add(`<${node.name}>`);
      node.children?.forEach(visit);
      return;
    }
    shape.marks.add(`{${node.name}}`);
    if (node.type === "choice") {
      const { name, kind, options } = node;
      shape.choices.push({ name, kind, options: new Set(options.keys()) });
      for (const option of node.options.values()) option.forEach(visit);
    }
  };
  nodes.forEach(visit);
  return shape;
}

function mismatch(source: Shape, translation: Shape | string, locale: string): string | undefined {
  if (typeof translation === "string") return translation;
  const missing = [...source.marks].filter((mark) => !translation.marks.has(mark));
  if (missing.length > 0) return `is missing ${missing.join(" ")}`;
  const unknown = [...translation.marks].filter((mark) => !source.marks.has(mark));
  if (unknown.length > 0) return `has unknown ${unknown.join(" ")}`;
  for (const { name, kind, options } of translation.choices) {
    if (kind === "select") continue;
    const absent = pluralCategories(locale, kind).filter((category) => !options.has(category));
    if (absent.length > 0) return `{${name}} is missing the forms ${absent.join(", ")}`;
  }
  return undefined;
}

function isLocaleTag(name: string): boolean {
  try {
    return Intl.getCanonicalLocales(name).length === 1;
  } catch {
    return false;
  }
}

function parseCatalog(text: string): Map<string, string> | undefined {
  let value: unknown;
  try {
    value = text.trim() ? JSON.parse(text) : {};
  } catch {
    return undefined;
  }
  if (typeof value !== "object" || value === null || Array.isArray(value)) return undefined;
  const entries = Object.entries(value);
  return entries.every(([, translation]) => typeof translation === "string")
    ? new Map(entries)
    : undefined;
}

function serialize(keys: string[], translations: Map<string, string>): string {
  if (keys.length === 0) return "{}\n";
  const lines = keys.map(
    (key) => `  ${JSON.stringify(key)}: ${JSON.stringify(translations.get(key) ?? "")}`,
  );
  return `{\n${lines.join(",\n")}\n}\n`;
}

function loaders(locales: string[]): string {
  const entries = new Map([[sourceLocale, "async () => ({ default: {} })"]]);
  for (const locale of locales) {
    entries.set(locale, `() => import("./${locale}.json", { with: { type: "json" } })`);
  }
  const lines = [...entries].map(([locale, loader]) => `  ${JSON.stringify(locale)}: ${loader},\n`);
  return `${header}import { activate } from "dicto";

const catalogs = {
  __proto__: null,
${lines.join("")}};

export const locales = Object.keys(catalogs);

export function isLocale(value) {
  return value in catalogs;
}

export function setLocale(locale, scope) {
  return activate(locale, catalogs[locale], scope);
}
`;
}

function declarations(locales: string[], messages: string[]): string {
  const names = [...new Set([sourceLocale, ...locales])].map((locale) => JSON.stringify(locale));
  const known = messages.map((message) => `\n      | ${JSON.stringify(message)}`);
  return `${header}export type Locale = ${names.join(" | ")};

export declare const locales: readonly Locale[];

export declare function isLocale(value: string): value is Locale;

/**
 * Loads a locale and makes it the active one. With \`scope\`, the locale is active only while
 * \`scope\` and what it awaits run, which keeps concurrent requests on a server apart.
 */
export declare function setLocale(locale: Locale): Promise<void>;
export declare function setLocale<T>(locale: Locale, scope: () => T): Promise<Awaited<T>>;

declare module "dicto" {
  interface Register {
    message:${known.length > 0 ? known.join("") : " never"};
  }
}
`;
}

function write(path: string, text: string, current?: string): void {
  if (text === (current ?? (existsSync(path) ? readFileSync(path, "utf8") : undefined))) return;
  writeFileSync(`${path}.tmp`, text);
  renameSync(`${path}.tmp`, path);
}
